#!/usr/bin/env python
"""
ThreatLens Stage 1: Dataset Validation Report Generator

Generates a human-readable Markdown report from the dataset validation results.
"""

import argparse
import sys
from pathlib import Path

# Ensure threatlens is importable
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from threatlens.config import DATA_CONFIG
from threatlens.preprocessing.metadata import MetadataManager


def format_report(metadata: dict) -> str:
    """Format metadata as Markdown report."""
    val = metadata.get("validation_report", {})
    splits = metadata.get("split_counts", {})
    schema = metadata.get("feature_schema", {})

    lines = [
        "# ThreatLens Stage 1 - Dataset Validation Report",
        "",
        f"**Generated**: {metadata.get('timestamp', 'N/A')}",
        f"**Random Seed**: {metadata.get('seed', 'N/A')}",
        "",
        "## Dataset Overview",
        "",
        f"- **Total Features**: {schema.get('total_features', 'N/A')}",
        f"- **Feature Groups**: {len(schema.get('feature_groups', {}))}",
        "",
        "### Feature Group Breakdown",
        "",
        "| Group | Start Index | End Index | Count |",
        "|-------|-------------|-----------|-------|",
    ]

    for name, info in schema.get("feature_groups", {}).items():
        lines.append(f"| {name} | {info['start_idx']} | {info['end_idx']} | {info['feature_count']} |")

    lines.extend([
        "",
        "## Validation Results",
        "",
        f"- **Overall Valid**: {'✅ YES' if val.get('is_valid') else '❌ NO'}",
        f"- **Total Samples**: {val.get('total_samples', 'N/A'):,}",
        f"- **Feature Dimension Valid**: {'✅' if val.get('valid_features_dim') else '❌'}",
        "",
        "### Label Distribution",
        "",
        "| Class | Count | Percentage |",
        "|-------|-------|------------|",
    ])

    dist = val.get("label_distribution", {})
    total = sum(dist.values())
    for label_str, count in sorted(dist.items()):
        try:
            label = int(label_str)
        except (ValueError, TypeError):
            label = label_str
        name = "Benign" if label == 0 else "Malicious" if label == 1 else f"Invalid ({label})"
        pct = (count / total * 100) if total > 0 else 0
        lines.append(f"| {name} | {count:,} | {pct:.2f}% |")

    lines.extend([
        "",
        f"- **Class Imbalance Ratio**: {val.get('class_imbalance_ratio', 'N/A'):.2f}:1",
        "",
        "### Data Quality Checks",
        "",
        f"- **Missing Values**: {val.get('missing_value_count', 0):,} ({val.get('missing_value_percentage', 0):.4f}%)",
        f"- **Infinite Values**: {val.get('infinite_value_count', 0):,}",
        f"- **Duplicate Records**: {val.get('duplicate_record_count', 0):,}",
        f"- **Corrupted Records**: {val.get('corrupted_record_count', 0):,}",
        f"- **Invalid Labels**: {val.get('invalid_label_count', 0):,}",
        "",
        "### Warnings",
        "",
    ])

    warnings = val.get("warnings", [])
    if warnings:
        for w in warnings:
            lines.append(f"- ⚠️ {w}")
    else:
        lines.append("- None")

    lines.extend([
        "",
        "### Errors",
        "",
    ])

    errors = val.get("errors", [])
    if errors:
        for e in errors:
            lines.append(f"- ❌ {e}")
    else:
        lines.append("- None")

    lines.extend([
        "",
        "## Split Summary",
        "",
        "| Split | Samples | Benign | Malicious | Benign % |",
        "|-------|---------|--------|-----------|----------|",
    ])

    for name, info in splits.items():
        benign = info.get("benign_count", 0)
        malicious = info.get("malicious_count", 0)
        total_split = benign + malicious
        pct = (benign / total_split * 100) if total_split > 0 else 0
        lines.append(f"| {name.capitalize()} | {info['samples']:,} | {benign:,} | {malicious:,} | {pct:.2f}% |")

    lines.extend([
        "",
        "## Preprocessing Configuration",
        "",
        f"- **Imputation Strategy**: {metadata.get('preprocessing_config', {}).get('impute_strategy', 'N/A')}",
        f"- **Scaler Type**: {metadata.get('preprocessing_config', {}).get('scaler_type', 'N/A')}",
        f"- **Centering**: {metadata.get('preprocessing_config', {}).get('with_centering', 'N/A')}",
        f"- **Scaling**: {metadata.get('preprocessing_config', {}).get('with_scaling', 'N/A')}",
        "",
        "---",
        f"*Report generated by ThreatLens Stage 1*",
    ])

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(
        description="Generate validation report from metadata"
    )
    parser.add_argument(
        "--metadata",
        type=Path,
        default=DATA_CONFIG.ARTIFACTS_DIR / "dataset_metadata.json",
        help="Path to metadata JSON file",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DATA_CONFIG.REPORTS_DIR / "validation_report.md",
        help="Output Markdown file",
    )
    args = parser.parse_args()

    if not args.metadata.exists():
        print(f"Error: Metadata file not found: {args.metadata}")
        sys.exit(1)

    metadata_mgr = MetadataManager()
    metadata = metadata_mgr.load_metadata(args.metadata.name)

    report = format_report(metadata)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(report, encoding="utf-8")

    print(f"Report saved to {args.output}")


if __name__ == "__main__":
    main()